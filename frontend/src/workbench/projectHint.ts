/**
 * 「没选项目」的用户提示。
 *
 * 后端各路由在拿不到项目根时统一回「未配置代码库」——那是**单库时代**的词，
 * 说的是内部的 code_root 指针。产品早已改成**项目制**（顶栏项目菜单 →「打开项目」
 * → 登记代码目录），前端各处也是按「未选择项目」说的（App.vue / AskSidebar.vue），
 * 于是同一件事在两个层用了两套词，模型/用户看到的提示也就对不上产品实际能做的事。
 *
 * 这里只做一件事：把后端那句旧词翻成**当前产品路径**能执行的下一步。
 * 不改后端那 154 处（它们是内部错误串，逐处改风险大且收益低）。
 */
export function noProjectHint(message: string): string {
  const text = String(message || '')
  if (/未配置代码库/.test(text)) {
    return '尚未选择项目，请在顶栏的项目菜单里「打开项目」并选择代码目录。'
  }
  return text
}
